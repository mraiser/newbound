#!/usr/bin/env python3
"""Generate a Markdown reference for every command in a Newbound store.

Reads `data/<lib>/` records read-only and writes one page per library,
an index (README.md) and missing-descriptions.md into the output folder.
Standard library only; runs anywhere Python 3.8+ runs (Linux, macOS,
Windows, Raspberry Pi). Output is deterministic: re-running on an
unchanged store produces byte-identical files.

Usage (from the repository root):

    python3 tools/gen-command-reference.py            # core libraries
    python3 tools/gen-command-reference.py --check    # exit 1 if stale

    # any other libraries, into a folder of your choice:
    python3 tools/gen-command-reference.py --data /path/to/data \\
        --lib mylib --out /path/to/docs/reference --title "My libraries"

By default the libraries are those in --data whose meta.json declares
`"root": "newbound_core"`. Hand-written descriptions for commands whose
store description is missing or thin are read from
`<out>/inferred-descriptions.json` and marked "(inferred)" on the page.
"""

import argparse
import hashlib
import json
import os
import re
import sys

# --------------------------------------------------------------------------
# UI words. A terminology rename is pending: change the words here only.
# --------------------------------------------------------------------------
LABELS = {
    "dev_app": "Development",      # the IDE app (library `dev`)
    "shelf": "Shelf",              # the IDE home: libraries and control cards
    "workbench": "Workbench",      # the editor surface for one control
    "commands_pane": "commands pane",
    "root": "Root",                # meta.json `root`: the crate a library builds into
    "library": "library",
    "libraries": "libraries",
    "control": "control",
    "controls": "controls",
    "command": "command",
    "commands": "commands",
}

CORE_ROOT = "newbound_core"
BASE_URL = "http://localhost:8080"   # http_port default in config.properties_example
COOKIE_JAR = "nb.cookies"
EXEC_APP = "app"                     # app.app.exec runs any command by id
GENERATED_MARK = "<!-- generated by tools/gen-command-reference.py; do not edit by hand -->"
INFERRED_FILE = "inferred-descriptions.json"
MIN_DESC_WORDS = 5                   # fewer words than this = description missing
SEE_ALSO_MAX = 6

# Example values used in the curl/websocket snippets, by declared type.
EXAMPLE_VALUES = {
    "Integer": 0,
    "Float": 0.0,
    "Boolean": False,
    "JSONObject": {},
    "JSONArray": [],
}


# --------------------------------------------------------------------------
# Store access (read-only)
# --------------------------------------------------------------------------
def record_path(data_dir, lib, rid):
    """ndata's layout: the id padded to 16 chars, split into 4-char folders."""
    pad = (rid + "_" * 16)[:16]
    return os.path.join(data_dir, lib, pad[0:4], pad[4:8], pad[8:12], pad[12:16], rid)


def read_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def read_text(path):
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def load_record(data_dir, lib, rid):
    p = record_path(data_dir, lib, rid)
    if not rid or not os.path.isfile(p):
        return None
    return read_json(p)


def read_properties(path):
    props = {}
    if not os.path.isfile(path):
        return props
    for line in read_text(path).split("\n"):
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        props[k.strip()] = v.strip()
    return props


def find_boot_control(runtime_dir, lib):
    """The app whose app.properties names this library: (app id, control id)."""
    if not runtime_dir or not os.path.isdir(runtime_dir):
        return None, None
    for app in sorted(os.listdir(runtime_dir)):
        props = read_properties(os.path.join(runtime_dir, app, "app.properties"))
        if props.get("ctldb") == lib and props.get("ctlid"):
            return props.get("id", app), props["ctlid"]
    return None, None


def code_of(data_dir, lib, impl_id, impl, lang):
    """The command body: the attachment for the language, else inline."""
    ext = {"rust": "rs", "python": "py"}.get(lang, lang)
    base = record_path(data_dir, lib, impl_id)
    for key in [ext, lang] + list(impl.get("attachmentkeynames", [])):
        p = base + "." + key
        if os.path.isfile(p):
            return read_text(p)
        if key in impl:
            v = impl[key]
            return v if isinstance(v, str) else json.dumps(v, sort_keys=True)
    return ""


def load_library(data_dir, runtime_dir, lib):
    meta_path = os.path.join(data_dir, lib, "meta.json")
    meta = read_json(meta_path) if os.path.isfile(meta_path) else {}
    controls_rec = load_record(data_dir, lib, "controls")
    controls = controls_rec["data"].get("list", []) if controls_rec else []
    app_id, boot_ctl = find_boot_control(runtime_dir, lib)

    ctls = []
    for c in controls:
        crec = load_record(data_dir, lib, c.get("id", ""))
        if not crec:
            continue
        cdata = crec.get("data", {})
        cmds = []
        for ref in cdata.get("cmd", []):
            mrec = load_record(data_dir, lib, ref.get("id", ""))
            if not mrec:
                continue
            mdata = mrec.get("data", {})
            lang = mdata.get("type") or "rust"
            impl_id = mdata.get(lang, "")
            irec = load_record(data_dir, lib, impl_id) or {}
            impl = irec.get("data", {})
            # read_command's rule: the command record's desc wins, else the impl's.
            desc = mdata.get("desc") if mdata.get("desc") is not None else impl.get("desc", "")
            groups = impl.get("groups") if "groups" in impl else mdata.get("groups")
            cmds.append({
                "lib": lib,
                "ctl": c["name"],
                "name": ref["name"],
                "id": ref["id"],
                "lang": lang,
                "desc": (desc or "").strip(),
                "params": [
                    {"name": p.get("name", ""), "type": p.get("type", "String"),
                     "desc": (p.get("desc") or "").strip()}
                    for p in impl.get("params", []) if isinstance(p, dict)
                ],
                "returntype": impl.get("returntype", ""),
                "groups": groups,
                "readers": mrec.get("readers"),
                "code": code_of(data_dir, lib, impl_id, impl, lang),
                "boot": c.get("id") == boot_ctl,
            })
        ctls.append({
            "name": c["name"],
            "desc": (cdata.get("desc") or "").strip(),
            "boot": c.get("id") == boot_ctl,
            "commands": sorted(cmds, key=lambda x: x["name"]),
        })
    ctls.sort(key=lambda x: x["name"])
    return {
        "name": lib,
        "desc": (meta.get("desc") or "").strip(),
        "version": meta.get("version"),
        "root": meta.get("root", ""),
        "app": app_id,
        "controls": ctls,
    }


# --------------------------------------------------------------------------
# Descriptions
# --------------------------------------------------------------------------
def code_hash(code):
    return hashlib.sha256(code.encode("utf-8")).hexdigest()[:16]


def full_name(c):
    return "%s.%s.%s" % (c["lib"], c["ctl"], c["name"])


def is_missing(desc):
    return len(desc.split()) < MIN_DESC_WORDS


def resolve_description(c, inferred):
    """Returns (author_text, inferred_text, status) for one command.

    status: "ok" | "inferred" (store text missing, inferred shown) |
    "supplemented" (thin store text kept, inferred detail added) |
    "missing" (store text missing, nothing inferred yet). A "-stale"
    suffix means the code changed since the inferred text was written.
    """
    entry = inferred.get(full_name(c))
    stale = ""
    if entry and entry.get("code_sha") != code_hash(c["code"]):
        stale = "-stale"
    if is_missing(c["desc"]):
        if entry and entry.get("mode") == "replace":
            return c["desc"], entry["desc"], "inferred" + stale
        return c["desc"], "", "missing"
    if entry and entry.get("mode") == "supplement" and entry.get("store_desc") == c["desc"]:
        return c["desc"], entry["desc"], "supplemented" + stale
    return c["desc"], "", "ok"


# --------------------------------------------------------------------------
# Markdown helpers
# --------------------------------------------------------------------------
HTML_TAGS = [(r"\s*<br\s*/?>\s*", "\n\n"), (r"</?(b|strong)>", "**"), (r"</?(i|em)>", "*"), (r"</?code>", "`")]


def md_text(s):
    """Turn the few HTML tags authors use into Markdown, then escape any
    other < outside `code spans` so GitHub keeps placeholders visible."""
    for pat, rep in HTML_TAGS:
        s = re.sub(pat, rep, s, flags=re.I)
    parts = s.split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "&lt;")
    s = "`".join(parts)
    return re.sub(r"(?m)^>", "\\>", s)


def md_cell(s):
    s = md_text(s).replace("|", "\\|")
    return re.sub(r"\s*\n\s*", " ", s).strip()


def slug(heading):
    """GitHub's heading anchor: lowercase, drop punctuation, spaces to '-'."""
    s = heading.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def anchor(c):
    return "#" + slug(full_name(c))


def required_label(p):
    if p["name"].startswith("nn_"):
        return "server"
    if p["type"] == "Any":
        return "no"
    return "yes"


def example_value(p):
    if p["type"] in EXAMPLE_VALUES:
        return EXAMPLE_VALUES[p["type"]]
    return "<%s>" % p["name"]


def caller_params(c):
    """Params a caller passes in a minimal call: required, not server-filled."""
    return [p for p in c["params"] if required_label(p) == "yes"]


def query_value(v):
    return v if isinstance(v, str) else json.dumps(v)


def call_examples(c, app):
    args = [(p["name"], example_value(p)) for p in caller_params(c)]
    lines = []
    if c["boot"] and app:
        path = "/%s/%s" % (app, c["name"])
        lines.append("**HTTP:** `GET %s`" % path)
        cmd = ["curl -b %s" % COOKIE_JAR]
        if args:
            cmd[0] += " -G"
        cmd.append('"%s%s"' % (BASE_URL, path))
        for k, v in args:
            cmd.append("--data-urlencode '%s=%s'" % (k, query_value(v)))
        frame = {"pid": "1", "bot": app, "cmd": c["name"], "params": dict(args)}
    else:
        path = "/%s/exec" % EXEC_APP
        lines.append("**HTTP:** `GET %s?lib=%s&id=%s&args=…` (via `app.app.exec`)"
                     % (path, c["lib"], c["id"]))
        cmd = ["curl -b %s -G" % COOKIE_JAR, '"%s%s"' % (BASE_URL, path),
               "--data-urlencode 'lib=%s'" % c["lib"],
               "--data-urlencode 'id=%s'" % c["id"],
               "--data-urlencode 'args=%s'" % json.dumps(dict(args), separators=(",", ":"))]
        frame = {"pid": "1", "bot": EXEC_APP, "cmd": "exec",
                 "params": {"lib": c["lib"], "id": c["id"], "args": dict(args)}}
    lines.append("")
    lines.append("```bash")
    lines.append(" \\\n  ".join(cmd))
    lines.append("```")
    lines.append("")
    lines.append("**WebSocket frame:**")
    lines.append("")
    lines.append("```text")
    lines.append("cmd " + json.dumps(frame, separators=(",", ":")))
    lines.append("```")
    return lines


def see_also(c, siblings):
    """Related commands in the same control. Small controls list every
    other command; larger ones list those sharing a name word or prefix,
    mentioning each other, or sharing parameters few siblings take."""
    others = [s for s in siblings if s["name"] != c["name"]]
    if len(others) <= SEE_ALSO_MAX:
        return others

    def pnames(x):
        return {p["name"] for p in x["params"] if not p["name"].startswith("nn_")}

    counts = {}
    for s in siblings:
        for n in pnames(s):
            counts[n] = counts.get(n, 0) + 1
    rare = {n for n, k in counts.items() if k * 3 <= len(siblings)}
    words = set(c["name"].split("_"))

    def mentions(text, name):
        return re.search(r"(?<![\w.])%s(?![\w])" % re.escape(name), text) is not None

    def score(s):
        w = len(words & set(s["name"].split("_"))) * 3
        w += 3 if len(os.path.commonprefix([c["name"], s["name"]])) >= 4 else 0
        w += 2 if mentions(c["desc"], s["name"]) or mentions(s["desc"], c["name"]) else 0
        w += len(pnames(c) & pnames(s) & rare)
        return w

    ranked = [s for s in sorted(others, key=lambda s: (-score(s), s["name"])) if score(s) >= 2]
    return sorted(ranked[:SEE_ALSO_MAX], key=lambda s: s["name"])



def default_libs(data_dir):
    libs = []
    for name in sorted(os.listdir(data_dir)):
        meta = os.path.join(data_dir, name, "meta.json")
        if os.path.isfile(meta) and read_json(meta).get("root") == CORE_ROOT:
            libs.append(name)
    return libs


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(here)
    ap = argparse.ArgumentParser(description="Generate the Newbound command reference.")
    ap.add_argument("--data", default=os.path.join(repo, "data"), help="store folder (default: ./data)")
    ap.add_argument("--runtime", default=None, help="runtime folder with <app>/app.properties (default: next to --data)")
    ap.add_argument("--lib", action="append", default=None, help="library to document (repeatable; default: the %s libraries)" % CORE_ROOT)
    ap.add_argument("--out", default=os.path.join(repo, "docs", "reference"), help="output folder (default: docs/reference)")
    ap.add_argument("--title", default="Newbound command reference", help="index page title")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if any page would change")
    a = ap.parse_args(argv)

    data_dir = os.path.abspath(a.data)
    runtime_dir = a.runtime or os.path.join(os.path.dirname(data_dir), "runtime")
    libs = a.lib or default_libs(data_dir)
    if not libs:
        print("no libraries found in %s" % data_dir, file=sys.stderr)
        return 2

    inferred_path = os.path.join(a.out, INFERRED_FILE)
    inferred = read_json(inferred_path) if os.path.isfile(inferred_path) else {}

    loaded = [load_library(data_dir, runtime_dir, lib) for lib in libs]
    statuses = {}
    files = {}
    for lib in loaded:
        files[lib["name"] + ".md"] = library_page(lib, inferred, statuses)
    regen = "python3 tools/gen-command-reference.py"
    if a.lib:
        regen += " --data <store folder> %s --out <this folder>" % " ".join("--lib " + n for n in libs)
        if a.title != ap.get_default("title"):
            regen += ' --title "%s"' % a.title
    files["README.md"] = index_page(loaded, statuses, a.title, regen)
    files["missing-descriptions.md"] = missing_page(statuses)

    unused = sorted(k for k in inferred if k not in statuses or statuses[k][1] == "ok")
    for k in unused:
        print("note: %s entry for %s is not used" % (INFERRED_FILE, k), file=sys.stderr)
    for k, v in sorted(statuses.items()):
        if v[1] == "missing":
            print("note: %s has no description and no inferred text" % k, file=sys.stderr)
        elif v[1].endswith("-stale"):
            print("note: inferred text for %s predates a code change" % k, file=sys.stderr)

    # Pages from an earlier run that this run no longer produces.
    stale_files = []
    if os.path.isdir(a.out):
        for name in sorted(os.listdir(a.out)):
            p = os.path.join(a.out, name)
            if name.endswith(".md") and name not in files and os.path.isfile(p):
                if read_text(p).startswith(GENERATED_MARK):
                    stale_files.append(p)

    changed = []
    for name, text in sorted(files.items()):
        p = os.path.join(a.out, name)
        old = read_text(p) if os.path.isfile(p) else None
        if old != text:
            changed.append(name)
            if not a.check:
                os.makedirs(a.out, exist_ok=True)
                with open(p, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    for p in stale_files:
        changed.append(os.path.basename(p) + " (removed)")
        if not a.check:
            os.remove(p)

    total = len(statuses)
    n_inf = sum(1 for s in statuses.values() if s[1] != "ok")
    print("%d libraries, %d commands, %d with inferred or missing descriptions; %d file(s) %s"
          % (len(loaded), total, n_inf, len(changed), "would change" if a.check else "written"))
    for name in changed:
        print("  " + name)
    return 1 if (a.check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())

def library_page(lib, inferred, statuses):
    L = LABELS
    out = [GENERATED_MARK, "", "# `%s` %s — %s reference" % (lib["name"], L["library"], L["command"]), ""]
    if lib["desc"]:
        out += [md_text(lib["desc"]), ""]
    facts = []
    if lib["version"] is not None:
        facts.append("Version %s" % lib["version"])
    if lib["root"]:
        facts.append("%s: `%s`" % (L["root"], lib["root"]))
    if lib["app"]:
        boot = [c["name"] for c in lib["controls"] if c["boot"]]
        if boot:
            facts.append("App `/%s/`, boot %s `%s`" % (lib["app"], L["control"], boot[0]))
    if facts:
        out += [" · ".join(facts), ""]
    out += ["[← Index](README.md)", ""]

    with_cmds = [c for c in lib["controls"] if c["commands"]]
    without = [c["name"] for c in lib["controls"] if not c["commands"]]
    out += ["## Contents", ""]
    if with_cmds:
        out += ["| %s | %s |" % (L["control"].capitalize(), L["commands"].capitalize()), "|---|---|"]
        for ctl in with_cmds:
            links = ", ".join("[%s](%s)" % (c["name"], anchor(c)) for c in ctl["commands"])
            out.append("| `%s` | %s |" % (ctl["name"], links))
    else:
        out.append("No %s." % L["commands"])
    out.append("")
    if without:
        out += ["%s without %s: %s." % (L["controls"].capitalize(), L["commands"],
                                        ", ".join("`%s`" % n for n in without)), ""]

    for ctl in with_cmds:
        out += ["## %s `%s`" % (L["control"].capitalize(), ctl["name"]), ""]
        if ctl["desc"]:
            out += [md_text(ctl["desc"]), ""]
        for c in ctl["commands"]:
            author, extra, status = resolve_description(c, inferred)
            statuses[full_name(c)] = (c, status, author, extra)
            out += ["### %s" % full_name(c), ""]
            groups = "`%s`" % c["groups"] if c["groups"] else "(not set)"
            readers = "`%s`" % json.dumps(c["readers"]) if c["readers"] is not None else "(not set)"
            out += ["**Language:** %s · **Returns:** `%s` · **Groups:** %s · **Readers:** %s"
                    % (c["lang"], c["returntype"] or "(none)", groups, readers), ""]
            if status == "missing":
                out += ["*No description in the store.*", ""]
            elif status.startswith("inferred"):
                out += ["*(inferred)* " + md_text(extra), ""]
            else:
                out += [md_text(author), ""]
                if extra:
                    out += ["*(inferred)* " + md_text(extra), ""]
            if c["params"]:
                out += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
                for p in c["params"]:
                    out.append("| `%s` | %s | %s | %s |" % (p["name"], p["type"], required_label(p), md_cell(p["desc"])))
            else:
                out.append("No parameters.")
            out.append("")
            out += call_examples(c, lib["app"])
            out += ["", "**MCP tool:** `%s-%s-%s`" % (c["lib"], c["ctl"], c["name"])]
            related = see_also(c, ctl["commands"])
            if related:
                out += ["", "**See also:** " + ", ".join("[%s](%s)" % (s["name"], anchor(s)) for s in related)]
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def index_page(libs, statuses, title, regen):
    L = LABELS
    total = len(statuses)
    inferred = sum(1 for s in statuses.values() if s[1].startswith("inferred"))
    supplemented = sum(1 for s in statuses.values() if s[1].startswith("supplemented"))
    missing = sum(1 for s in statuses.values() if s[1] == "missing")
    out = [GENERATED_MARK, "", "# %s" % title, ""]
    out += ["One page per %s: every %s's full name, language, description, parameters, "
            "return type, groups and readers as stored, and how to call it." % (L["library"], L["command"]), ""]
    out += ["Regenerate after changing the store:", "", "```bash", regen, "```", ""]

    out += ["## %s" % L["libraries"].capitalize(), "",
            "| %s | %s | %s | Description |" % (L["library"].capitalize(), L["controls"].capitalize(), L["commands"].capitalize()),
            "|---|---|---|---|"]
    for lib in libs:
        n_ctl = sum(1 for c in lib["controls"] if c["commands"])
        n_cmd = sum(len(c["commands"]) for c in lib["controls"])
        out.append("| [`%s`](%s.md) | %d | %d | %s |" % (lib["name"], lib["name"], n_ctl, n_cmd, md_cell(lib["desc"])))
    out.append("")
    out += ["**%d %s.** Descriptions written by the author: %d. Inferred from the code "
            "and marked *(inferred)*: %d. Thin author text with inferred detail added: %d. "
            "Still missing: %d. See [missing-descriptions.md](missing-descriptions.md)."
            % (total, L["commands"], total - inferred - missing, inferred, supplemented, missing), ""]

    out += ["## Reading a %s entry" % L["command"], "",
            "- **Full name** is `%s.%s.%s`." % (L["library"], L["control"], L["command"]),
            "- **Language** is the language the body is written in (rust, flow, python, js, java).",
            "- **Returns** is the declared return type. A `FLAT` result is the command's own object "
            "with `status` added; a `String` result arrives as `{\"status\":\"ok\",\"msg\":…}`; any "
            "other type arrives as `{\"status\":\"ok\",\"data\":…}`. Errors are `{\"status\":\"err\",\"msg\":…}`.",
            "- **Groups** is the %s's comma-separated `groups` string and **Readers** the `readers` "
            "array on its record, both shown exactly as stored." % L["command"],
            "- **Required**: `yes` parameters must be sent. `no` marks `Any` parameters, which arrive "
            "as `null` when left out over HTTP, WebSocket or `app.app.exec`; MCP tools list every "
            "declared parameter as required, so pass `null` there. `server` marks `nn_` parameters, "
            "which the server fills from the request (`nn_sessionid` is the caller's session).",
            "- **See also** lists related %s in the same %s." % (L["commands"], L["control"]),
            ""]

    out += ["## Calling a %s" % L["command"], "",
            "The examples assume an instance on `%s` (`http_port` in `config.properties`). "
            "Sign in once and keep the session cookie:" % BASE_URL, "",
            "```bash",
            "curl -c %s -b %s -G \"%s/app/login\" \\\n  --data-urlencode 'user=admin' --data-urlencode 'pass=<password>'"
            % (COOKIE_JAR, COOKIE_JAR, BASE_URL),
            "```", "",
            "Every response sets the `sessionid` cookie; the examples send it back with `-b %s`. "
            "They use POSIX shell quoting; in PowerShell call `curl.exe` and adjust the quotes." % COOKIE_JAR, "",
            "**HTTP.** The %s of an app's boot %s answer at `/<app>/<%s>`, with parameters in the "
            "query string (JSON values as JSON text). Every other %s runs through `app.app.exec`: "
            "`/app/exec?lib=<%s>&id=<%s id>&args=<JSON object>`. The %s id is shown in each example; "
            "`exec` passes `nn_sessionid` but no other `nn_` parameter."
            % (L["commands"], L["control"], L["command"], L["command"], L["library"], L["command"], L["command"]), "",
            "**WebSocket.** Open a websocket to any app page (for example `ws://localhost:8080/app/index.html`) "
            "with the subprotocol `newbound`, sending the session cookie. Each request is one text frame: "
            "`cmd ` followed by JSON with a `pid` you choose, the app as `bot`, the %s as `cmd`, and `params`. "
            "The reply is a JSON frame carrying the same `pid`. Adding `\"peer\":\"<peer uuid>\"` runs the "
            "%s on a connected peer." % (L["command"], L["command"]), "",
            "**MCP.** `newbound mcp` serves every %s as a tool named `<%s>-<%s>-<%s>`."
            % (L["command"], L["library"], L["control"], L["command"]), "",
            "**Source.** In the %s app, open the %s on the %s, open the %s on the %s, and pick the "
            "%s in the %s." % (L["dev_app"], L["library"], L["shelf"], L["control"], L["workbench"],
                               L["command"], L["commands_pane"]), ""]
    return "\n".join(out).rstrip("\n") + "\n"


def missing_page(statuses):
    L = LABELS
    rows = sorted((k, v) for k, v in statuses.items() if v[1] != "ok")
    out = [GENERATED_MARK, "", "# Missing %s descriptions" % L["command"], ""]
    out += ["%s whose store description is missing or too thin. Each should get a proper "
            "description in the store, written with `dev.code.set_command_meta` (pass the new `desc`; "
            "an empty `groups` leaves the groups as they are). Until then the reference shows text "
            "inferred from the code, marked *(inferred)*." % L["commands"].capitalize(), ""]
    out += ["Inferred text lives in `%s` next to these pages, keyed by full name, with a hash "
            "of the code it was written from. *stale* means the code has changed since." % INFERRED_FILE, ""]
    if not rows:
        out += ["None.", ""]
        return "\n".join(out).rstrip("\n") + "\n"
    out += ["| %s | Store description | Reference shows |" % L["command"].capitalize(), "|---|---|---|"]
    shows = {
        "inferred": "inferred description",
        "supplemented": "store text + inferred detail",
        "missing": "nothing yet",
    }
    for name, (c, status, author, extra) in rows:
        base = status.replace("-stale", "")
        note = shows[base] + (" (stale)" if status.endswith("-stale") else "")
        store = md_cell(author) if author else "(empty)"
        out.append("| [`%s`](%s.md%s) | %s | %s |" % (name, c["lib"], anchor(c), store, note))
    out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


